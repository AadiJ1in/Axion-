import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createMovementGameController, MOVEMENT_EVENT } from '../src/movement-game.js';

const js=readFileSync('src/patient-game-polish.js','utf8');
const css=readFileSync('src/patient-game-polish.css','utf8');
const ui=readFileSync('src/adventure-ui.js','utf8');
const index=readFileSync('index.html','utf8');

assert.ok(!js.includes('MutationObserver'), 'patient polish must remain observer-free');
assert.ok(js.includes('acknowledgeSafety'), 'explicit resume must release the safety UI latch');
assert.ok(js.includes('REST_SYNC_INTERVAL_MS = 250'), 'rest countdown cadence must remain explicit and lightweight');
assert.ok(js.includes('startPolishTimer();'), 'rest synchronization must restart after a page restore');
assert.ok(!js.includes("}, { once:true });"), 'page lifecycle cleanup must survive repeated bfcache hide/show cycles');
assert.ok(js.includes('presentationFrame = 0;'), 'cancelled presentation frames must release the scheduling latch');
assert.ok(js.includes('function stopPresentationLifecycle()'), 'page lifecycle cleanup must be centralized and reusable');
assert.ok(js.includes('LATE_CLINIC_SYNC_WINDOW_MS = 12000'), 'late clinic presentation polling must be bounded');
assert.ok(js.includes('startLateClinicSyncWindow();'), 'bounded clinic synchronization must start after initial render');
assert.ok(js.includes("const lab = document.querySelector('.adventure-lab')"), 'rest polling must exit immediately outside Movement Lab');
assert.ok(js.includes("document.addEventListener('click', () => window.setTimeout(schedulePresentationHierarchy, 0))"), 'every clinical control click must preserve the proven post-click presentation sync');
assert.ok(js.includes('node.textContent !== value'), 'rest-state DOM writes should skip unchanged text');
assert.ok(css.includes("REST TIME LEFT"), 'rest overlay must clearly label its countdown');
assert.ok(css.includes("url('/axion-kingdom-world.webp')"), 'roadmap tail must continue the kingdom artwork');
assert.ok(css.includes('.camera-pane video{opacity:0'), 'empty camera media is hidden until active');
assert.ok(css.includes('contain:layout paint'), 'game viewport must isolate canvas layout and paint work');
assert.ok(!css.includes('cover fixed'), 'Movement Lab background must not force fixed-attachment repaints');
assert.ok(!css.includes(':has('), 'active game polish must avoid relational selectors in the animation path');
assert.ok(css.includes('width:min(520px,calc(100% - 28px))'), 'rest card must stay inside narrow viewports');
assert.ok(css.includes('body.axion-adventure-lab-surface .topbar'), 'live-camera topbar must use the low-compositing presentation surface');
assert.ok(css.includes('-webkit-backdrop-filter:none!important'), 'live-camera overlays must disable Safari backdrop compositing explicitly');
assert.ok(ui.includes('HOW TO PLAY'), 'movement games must explain their controls');
assert.ok(index.includes('./src/patient-game-polish.css'), 'polish stylesheet must load last');
assert.ok(index.includes('./src/patient-game-polish.js'), 'observer-free polish helper must load');

const stable=createMovementGameController({exerciseKey:'chin_tuck',targetReps:2});
stable.setMode('game');
stable.consume({type:MOVEMENT_EVENT.MOVEMENT_PROGRESS,progress:.50,stage:'down'});
const first=stable.getState().movement;
assert.ok(first>0 && first<.5, 'visual motion should ease toward raw movement instead of snapping');
stable.consume({type:MOVEMENT_EVENT.MOVEMENT_PROGRESS,progress:.51,stage:'down'});
assert.ok(Math.abs(stable.getState().movement-first)<.08, 'nearby pose frames should not create a large visual jump');
assert.equal(stable.getState().completed,0,'visual smoothing can never create a clinical rep');
stable.consume({type:MOVEMENT_EVENT.SAFETY_FLAG});
assert.equal(stable.getState().paused,true);
assert.equal(stable.getState().safetyFlagged,true);
stable.acknowledgeSafety();
assert.equal(stable.getState().paused,true,'acknowledgement alone does not resume clinical tracking');
assert.equal(stable.getState().safetyFlagged,false,'explicit acknowledgement allows the existing resume handler to proceed');

console.log('Movement Lab rest clarity, resume recovery, visual smoothing, presentation stability, and roadmap-tail checks passed.');
